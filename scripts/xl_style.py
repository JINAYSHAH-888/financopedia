"""Shared Excel styling and layout helpers for every Financopedia model type.

One place for the colour key, so a DCF, an LBO, an IPO and a three-statement
model all read the same way: blue is something you can change, black is
something the workbook worked out, amber is an estimate.
"""

from __future__ import annotations

from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

F_INPUT = Font(color="0000CC", name="Calibri", size=11)
F_ESTIMATE = Font(color="B45F06", name="Calibri", size=11, italic=True)
F_FORMULA = Font(color="000000", name="Calibri", size=11)
F_HEAD = Font(bold=True, color="FFFFFF", name="Calibri", size=11)
F_TITLE = Font(bold=True, size=14, name="Calibri")
F_SUB = Font(bold=True, name="Calibri", size=11)
F_NOTE = Font(italic=True, color="666666", name="Calibri", size=9)
F_BOLDOUT = Font(bold=True, size=12, name="Calibri")

FILL_HEAD = PatternFill("solid", fgColor="1F3864")
FILL_BAND = PatternFill("solid", fgColor="EEF2F8")
FILL_EST = PatternFill("solid", fgColor="FFF3E0")
FILL_OUT = PatternFill("solid", fgColor="E8F5E9")
FILL_HIST = PatternFill("solid", fgColor="F5F5F5")

THIN = Side(style="thin", color="C8CDD6")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

NUM = "#,##0.0"
NUM0 = "#,##0"
PCT = "0.0%"
PCT2 = "0.00%"
MULT = "0.0x"
CUR = "#,##0.00"
DAYS = "#,##0"

NO_ADVICE = ("Research and analysis only. This workbook expresses no view on "
             "whether to buy, sell or transact.")
NOT_ADVICE = ("Not financial advice and not produced by a licensed advisor. "
              "Assumptions are estimates and will be wrong to some degree; the "
              "sensitivity tab exists to show by how much.")


def col(n: int) -> str:
    """1-indexed column number to letter."""
    return get_column_letter(n)


def head(ws, row, labels, start=1):
    for j, text in enumerate(labels):
        c = ws.cell(row=row, column=start + j, value=text)
        c.font, c.fill = F_HEAD, FILL_HEAD
        c.alignment = Alignment(horizontal="center", vertical="center")


def put(ws, addr, value, *, font=F_FORMULA, fmt=None, fill=None, border=True):
    c = ws[addr] if isinstance(addr, str) else addr
    c.value = value
    c.font = font
    if fmt:
        c.number_format = fmt
    if fill:
        c.fill = fill
    if border:
        c.border = BOX
    return c


def label(ws, row, text, *, col_idx=1, font=F_SUB, indent=0):
    c = ws.cell(row=row, column=col_idx, value=("    " * indent) + text)
    c.font, c.border = font, BOX
    return c


def note(ws, row, col_idx, text):
    c = ws.cell(row=row, column=col_idx, value=text)
    c.font = F_NOTE
    c.alignment = Alignment(wrap_text=True, vertical="top")
    return c


def widths(ws, mapping):
    for c, w in mapping.items():
        ws.column_dimensions[c].width = w


def year_widths(ws, n_cols, first_col=2, label_w=38, year_w=13, extra=None):
    ws.column_dimensions["A"].width = label_w
    for k in range(n_cols):
        ws.column_dimensions[col(first_col + k)].width = year_w
    if extra:
        ws.column_dimensions[col(first_col + n_cols)].width = extra


def readme_sheet(wb, spec, model_label, extra_rows=None):
    ws = wb.create_sheet("README")
    m = spec["meta"]
    ws["A1"] = f"{m['name']} ({m['ticker']}) — {model_label}"
    ws["A1"].font = F_TITLE
    rows = [
        ("Built", m["as_of"]),
        ("Currency", m["currency"]),
        ("Units", m["units"]),
        ("Fiscal year end", m.get("fiscal_year_end", "not stated")),
        ("Generated by", "Financopedia build_model.py"),
        ("", ""),
        ("Colour key", "Blue = input you can change · Black = formula · "
                       "Amber italic = estimated input"),
        ("Structure", "Every figure outside INPUTS and HISTORICALS is a formula. "
                      "Change an input, the model moves."),
        ("CHECKS tab", "Live assertions recomputing the model's identities. "
                       "All must read PASS."),
    ]
    rows += list(extra_rows or [])
    rows += [("", ""), ("Scope", NO_ADVICE), ("Not advice", NOT_ADVICE)]
    for i, (k, v) in enumerate(rows, start=3):
        ws.cell(row=i, column=1, value=k).font = F_SUB
        ws.cell(row=i, column=2, value=v)
    widths(ws, {"A": 18, "B": 112})
    return ws


def checks_sheet(wb, checks):
    """checks: list of (label, formula, why). Adds an OVERALL roll-up."""
    ws = wb.create_sheet("CHECKS")
    ws["A1"] = "CHECKS — live assertions, recomputed by Excel"
    ws["A1"].font = F_TITLE
    ws["A2"] = ("Every row must read PASS. These recompute identities "
                "independently of the cells they test.")
    ws["A2"].font = F_NOTE
    head(ws, 3, ["Check", "Result", "What it proves"])
    for n, (lab, formula, why) in enumerate(checks):
        r = 4 + n
        label(ws, r, lab)
        put(ws, f"B{r}", formula, font=Font(bold=True))
        note(ws, r, 3, why)
    last = 3 + len(checks)
    r = last + 2
    ws.cell(row=r, column=1, value="OVERALL").font = F_TITLE
    put(ws, f"B{r}",
        f'=IF(COUNTIF(B4:B{last},"FAIL")=0,"ALL PASS","FAILURES PRESENT")',
        font=F_BOLDOUT, fill=FILL_OUT)
    widths(ws, {"A": 46, "B": 20, "C": 66})
    return ws
